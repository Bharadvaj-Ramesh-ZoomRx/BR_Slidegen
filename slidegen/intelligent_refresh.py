"""
intelligent_refresh.py — Intelligent slide refresh orchestrated by Claude Code.

Pipeline:
  1. embed-config: Write a lightweight config into the PPTX as a Custom XML Part
     (slide IDs, data source assignments, data_sources catalog)
  2. read: Extract visual context from slides for Claude Code interpretation
  3. refresh-deck: Read embedded config + spec.json, fetch data, refresh all slides
  4. headline: Write data-grounded headlines into refreshed slides

The PPTX carries an embedded config (source of truth for structure).
The spec.json carries detailed per-component mappings (generated by Claude Code).
When the deck is edited in PowerPoint (reorder/add/delete), the embedded config
is used to reconcile spec.json automatically.

Usage:
    python -m slidegen.intelligent_refresh embed-config --pptx deck.pptx --config config.yaml
    python -m slidegen.intelligent_refresh read --pptx deck.pptx [--slide 0]
    python -m slidegen.intelligent_refresh refresh-deck --spec deck.json
    python -m slidegen.intelligent_refresh headline --pptx deck.pptx --slide 0 --text "..."
"""
