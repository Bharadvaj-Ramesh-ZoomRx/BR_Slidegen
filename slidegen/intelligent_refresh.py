def main():
    import argparse

    parser = argparse.ArgumentParser(
        description="Intelligent slide refresh pipeline",
    )
    sub = parser.add_subparsers(dest="command")

    # ── embed-config: scan PPTX and write config into it ──
    p_embed = sub.add_parser("embed-config", help="Generate and embed config into PPTX")
