def write_headline(pptx_path: str, slide_index: int, headline_text: str) -> None:
    """Write a headline into the slide's headline text shape (top area, largest text).

    Finds the headline shape: text shape in the top 1.5" zone with the longest text.
    Clears all runs, writes the new headline text into the first run preserving formatting.
    Saves the PPTX.
    """
    prs = Presentation(pptx_path)
    slide = prs.slides[slide_index]

    # Find headline shape: text shapes in top 1.5" zone, pick the one with longest text
    TOP_ZONE = 1.5  # inches
    candidates = []
    for shape in slide.shapes:
        if not shape.has_text_frame:
            continue
        top_in = _in(shape.top)
        if top_in > TOP_ZONE:
            continue
        text = shape.text_frame.text.strip()
        if text:
            candidates.append((shape, len(text)))

    if not candidates:
        raise ValueError(
            f"No text shapes found in top {TOP_ZONE}\" zone of slide {slide_index}"
        )

    # Pick shape with longest existing text (most likely the headline)
    headline_shape = max(candidates, key=lambda x: x[1])[0]

    # Preserve first paragraph's first run formatting, clear everything else
    first_para = headline_shape.text_frame.paragraphs[0]

    # Save formatting from first run if it exists
    saved_font = None
    if first_para.runs:
        run = first_para.runs[0]
        saved_font = {
            "bold": run.font.bold,
            "italic": run.font.italic,
            "size": run.font.size,
            "color_rgb": run.font.color.rgb if run.font.color and run.font.color.rgb else None,
            "name": run.font.name,
        }

    # Clear all runs in all paragraphs
    for para in headline_shape.text_frame.paragraphs:
        for run in para.runs:
            run.text = ""

    # Write new headline text into first run of first paragraph
    if first_para.runs:
        first_para.runs[0].text = headline_text
    else:
        # No runs exist — add one
        run = first_para.add_run()
        run.text = headline_text
        if saved_font:
            if saved_font["bold"] is not None:
                run.font.bold = saved_font["bold"]
            if saved_font["italic"] is not None:
                run.font.italic = saved_font["italic"]
            if saved_font["size"] is not None:
                run.font.size = saved_font["size"]
            if saved_font["color_rgb"] is not None:
                run.font.color.rgb = saved_font["color_rgb"]
            if saved_font["name"] is not None:
                run.font.name = saved_font["name"]

    prs.save(pptx_path)


# ══════════════════════════════════════════════════════════════════════════════
# Deck-level refresh from a single spec JSON
# ══════════════════════════════════════════════════════════════════════════════

def refresh_deck_from_spec(
    spec_path: str,
    pptx_path: str = None,
    output_path: str = None,
    *,
    force_fresh: bool = False,
    max_workers: int = 6,
) -> dict:
    """Refresh a deck using a single spec JSON file.

    Spec JSON format:
    {
      "source_deck": "deck.pptx",
      "data_sources": {
        "source_key": {"project_id": ..., "reporting_plan_id": ..., ...}
      },
      "slides": [
        {"slide_index": 4, "data_source": "source_key", "components": [...]}
      ]
    }

    Fetches data per data_source (cached), then refreshes each slide's components.
    Returns results dict.
    """
    spec = json.loads(Path(spec_path).read_text(encoding="utf-8"))
    spec_dir = Path(spec_path).parent

    # Resolve paths
    if pptx_path is None:
        pptx_path = str(spec_dir / spec["source_deck"])
    if output_path is None:
        stem = Path(spec["source_deck"]).stem
        ext = Path(spec["source_deck"]).suffix
        output_path = str(spec_dir / f"Output_{stem}{ext}")

    # Reconcile spec against embedded config if present
    embedded = read_embedded_config(pptx_path)
    if embedded:
        result = reconcile_spec_with_config(spec, embedded)
        spec = result["spec"]
        changes = result["changes"]
        if changes["reordered"]:
            print(f"  Reconciled: {len(changes['reordered'])} slides reordered")
        if changes["added"]:
            print(f"  Reconciled: {len(changes['added'])} slides added (need interpretation)")
        if changes["deleted"]:
            print(f"  Reconciled: {len(changes['deleted'])} slides deleted (removed from spec)")

    data_sources = spec.get("data_sources", {})
    slides = spec.get("slides", [])

    # Read source series order for all slides
    src_prs = Presentation(pptx_path)
    src_series_by_slide = {}
    for slide_spec in slides:
        si = slide_spec["slide_index"]
        if si < len(src_prs.slides):
            src_series_by_slide[si] = {}
            for shape in src_prs.slides[si].shapes:
                if shape.has_chart:
                    src_series_by_slide[si][shape.name] = [
                        str(s.name) for s in shape.chart.plots[0].series
                    ]

    # Clone source -> output
    shutil.copy2(pptx_path, output_path)
    prs = Presentation(output_path)

    # Cache fetched data by data_source key
    data_cache = {}

    # ── Parallel pre-fetch of every unique data_source referenced in the spec
    # Honors disk cache inside fetch_synapse_data (skips API entirely on hit).
    # Lazy fetches below remain as a fallback for keys not enumerated here.
    needed_keys: list[str] = []
    seen_keys: set[str] = set()
    for _slide_spec in slides:
        _slide_ds = _slide_spec.get("data_source")
        if _slide_ds and _slide_ds in data_sources and _slide_ds not in seen_keys:
            seen_keys.add(_slide_ds); needed_keys.append(_slide_ds)
        for _comp in _slide_spec.get("components", []):
            _cds = _comp.get("data_source")
            if _cds and _cds in data_sources and _cds not in seen_keys:
                seen_keys.add(_cds); needed_keys.append(_cds)

    if needed_keys:
        print(f"  Pre-fetching {len(needed_keys)} data_source(s) "
              f"(parallel, force_fresh={force_fresh})")

        def _fetch_one(k: str):
            try:
                _, _df = fetch_synapse_data(data_sources[k], force_fresh=force_fresh)
                return k, _df, None
            except Exception as exc:
                return k, pd.DataFrame(), exc

        workers = max(1, min(max_workers, len(needed_keys)))
        with ThreadPoolExecutor(max_workers=workers) as pool:
            for k, df_k, err in pool.map(_fetch_one, needed_keys):
                if err is not None:
                    print(f"    [warn] {k}: {err}")
                    data_cache[k] = pd.DataFrame()
                else:
                    data_cache[k] = df_k
                    print(f"    {k}: {len(df_k)} records")

    # Cache the full known-wave set per data_source — Fix L/M uses this for
    # value-driven wave-label detection in selectedColumns. Computed lazily
    # by stripping wave filters from the lineage and re-fetching once per ds.
    known_waves_cache: dict[str, set[str]] = {}

    def _get_known_wave_labels(ds_key: str) -> set[str]:
        if ds_key in known_waves_cache:
            return known_waves_cache[ds_key]
        labels: set[str] = set()
        lineage = data_sources.get(ds_key, {})
        if lineage:
            try:
                _, full_df = fetch_synapse_data({
                    "project_id": lineage.get("project_id"),
                    "reporting_plan_id": lineage.get("reporting_plan_id"),
                    "analysis_ids": list(lineage.get("analysis_ids") or []),
                    "segment_ids": list(lineage.get("segment_ids") or []),
                    "dynamic_latest_n": 0,
                    "static_time_period_ids": [],
                    "static_time_period_names": [],
                    "include_live_wave": True,
                }, force_fresh=force_fresh)
                if not full_df.empty and "time_period_name" in full_df.columns:
                    raw = full_df["time_period_name"].astype(str).unique()
                    labels = set(raw)
                    # Mirror the mapper's "Project Wave " -> "Wave " strip so
                    # rewrites that emit the stripped form still detect both.
                    stripped = full_df["time_period_name"].astype(str).str.replace(
                        r"^Project Wave ", "Wave ", regex=True,
                    ).unique()
                    labels |= set(stripped)
            except Exception as exc:
                print(f"  [warn] known-wave fetch failed for {ds_key}: {exc}")
        known_waves_cache[ds_key] = labels
        return labels

    all_results = {"slides": [], "output": output_path}
    ns_c = "http://schemas.openxmlformats.org/drawingml/2006/chart"

    for slide_spec in slides:
        si = slide_spec["slide_index"]
        ds_key = slide_spec.get("data_source")
        if si >= len(prs.slides):
            all_results["slides"].append({"slide_index": si, "error": "out of range"})
            continue

        slide = prs.slides[si]

        # Fetch data (cached by data_source key) — fallback if pre-fetch missed it
        if ds_key and ds_key not in data_cache:
            lineage = data_sources.get(ds_key, {})
            if lineage:
                print(f"  Fetching data_source '{ds_key}': project={lineage.get('project_id')}, "
                      f"analysis={lineage.get('analysis_ids')}")
                records, df = fetch_synapse_data(lineage, force_fresh=force_fresh)
                data_cache[ds_key] = df
                print(f"    -> {len(records)} records")
            else:
                data_cache[ds_key] = pd.DataFrame()

        df = data_cache.get(ds_key, pd.DataFrame())
        # Allow slides where every component has its own data_source override
        has_comp_ds = any(c.get("data_source") for c in slide_spec.get("components", []))
        if df.empty and not has_comp_ds:
            all_results["slides"].append({"slide_index": si, "error": "no data"})
            continue

        # Index shapes — list of (name, left_in, top_in, shape, used_flag).
        # Connector "split-viz" puts 15+ chart shapes on one slide ALL with the
        # same name (e.g. "Main chart" × 15). A name-only dict collapses them
        # to one entry; per-component refresh then writes to the same shape 15
        # times, leaving the other 14 with stale source data. Match by name AND
        # position (per-component spec carries left/top in inches), and mark a
        # shape as "used" once it's been claimed by a component.
        def _safe_shape_id(s):
            try:
                return int(s.shape_id)
            except Exception:
                return None

        # Walk groups so charts/tables nested in a Group get included in
        # the shape pool. Without this, a tagged chart inside a group is
        # never found by _claim_shape -> chart never refreshes.
        all_leaf_shapes = list(walk_shapes_recursive(slide.shapes))
        chart_shape_pool: list[dict] = [
            {"name": s.name,
             "shape_id": _safe_shape_id(s),
             "left_in": (s.left or 0) / 914400,
             "top_in": (s.top or 0) / 914400,
             "shape": s, "used": False}
            for s in all_leaf_shapes if s.has_chart
        ]
        table_shape_pool: list[dict] = [
            {"name": s.name,
             "shape_id": _safe_shape_id(s),
             "left_in": (s.left or 0) / 914400,
             "top_in": (s.top or 0) / 914400,
             "shape": s, "used": False}
            for s in all_leaf_shapes if s.has_table
        ]

        def _claim_shape(pool: list[dict], name: str,
                         pos: dict | None = None,
                         shape_id: int | None = None) -> object | None:
            """Find an unused shape, preferring intrinsic XML id over
            name+position. Marks the chosen shape used so later components
            on the same slide don't re-claim it.

            Resolution order (each tier only fires when the previous found
            no candidates):
              1. shape_id exact match — unambiguous; safe even when shape
                 names collide on the same slide (Repatha ATU 11/12).
              2. name match + closest-position pick — legacy path for
                 specs that don't carry shape_id.
              3. fallback: any matching name (re-use), preserves prior
                 behavior on split-viz slides where the pool is exhausted.
            """
            # Tier 1: shape_id exact match (most specs from refresh_pipeline)
            if shape_id is not None:
                for e in pool:
                    if e["shape_id"] == shape_id and not e["used"]:
                        e["used"] = True
                        return e["shape"]
                # Allow re-use when already claimed (split-viz components
                # on same shape — rare but supported).
                for e in pool:
                    if e["shape_id"] == shape_id:
                        return e["shape"]

            # Tier 2: name match, position-tiebreak
            candidates = [e for e in pool if e["name"] == name and not e["used"]]
            if not candidates:
                # Tier 3: name match (allow re-use)
                fallback = next((e for e in pool if e["name"] == name), None)
                return fallback["shape"] if fallback else None
            if len(candidates) == 1 or pos is None:
                candidates[0]["used"] = True
                return candidates[0]["shape"]
            target_l = float(pos.get("left", 0) or 0)
            target_t = float(pos.get("top", 0) or 0)
            best = min(
                candidates,
                key=lambda e: abs(e["left_in"] - target_l) + abs(e["top_in"] - target_t),
            )
            best["used"] = True
            return best["shape"]

        # Backwards-compat dict aliases for code paths below that haven't
        # been converted yet (table refresh + dual-mode tables). Reads from
        # these still work for non-collision slides; collision-prone code
        # uses _claim_shape().
        chart_shapes = {s.name: s for s in all_leaf_shapes if s.has_chart}
        table_shapes = {s.name: s for s in all_leaf_shapes if s.has_table}
        src_chart_series = src_series_by_slide.get(si, {})

        slide_results = {"slide_index": si, "charts": [], "tables": []}

        # ── Ambiguous-tag detection ──
        # When 2+ chart shapes on a slide carry IDENTICAL connector tag
        # configs (same data_source, same raw_pivot_config, same
        # raw_mapping_config, same Filters/selectedRows), the spec
        # cannot tell them apart — they all run the same pivot and
        # would receive the same refreshed values. If the source had
        # *different* values for them (Repatha ATU slide 73: 4 charts
        # showing 4 different intent measures), writing the same data
        # to all 4 is wrong. Detect this fingerprint clash and mark
        # those components so the chart-write path preserves source
        # values instead of leaking the same data into every chart.
        import json as _json
        chart_components = [
            c for c in slide_spec.get("components", [])
            if c.get("type") == "chart"
        ]
        _ambiguous_chart_keys: set[str] = set()
        if len(chart_components) >= 2:
            fingerprint_to_names: dict[str, list[str]] = {}
            for _c in chart_components:
                fp = _json.dumps({
                    "ds": _c.get("data_source"),
                    "pc": _c.get("raw_pivot_config"),
                    "mc": _c.get("raw_mapping_config"),
                    "split_order": _c.get("split_order"),
                }, sort_keys=True, default=str)
                fingerprint_to_names.setdefault(fp, []).append(_c.get("name", ""))
            for fp, names in fingerprint_to_names.items():
                if len(names) >= 2:
                    # Compare source values across these shapes — if any
                    # differ the tags are ambiguous (genuinely different
                    # display intent, but tag config can't differentiate).
                    src_value_sigs = set()
                    for nm in names:
                        sig = src_series_by_slide.get(si, {}).get(nm)
                        if sig is not None:
                            src_value_sigs.add(repr(sig))
                    if len(src_value_sigs) > 1:
                        for nm in names:
                            _ambiguous_chart_keys.add(nm)

        # ── Split-viz applyTranspose alignment ──
        # When a slide has multiple chart shapes sharing a name + split_order
        # 0..N, Connector applies the lead (split=0) shape's applyTranspose
        # uniformly across the group at render time. Source decks sometimes
        # carry inconsistent values across the group (lead True, followers
        # False) — following the tag literally produces mixed orientations.
        # Copy the lead's applyTranspose into all members.
        _split_lead_transpose: dict[str, bool] = {}
        for _comp in slide_spec.get("components", []):
            if _comp.get("type") != "chart":
                continue
            if _comp.get("split_order") == 0:
                _name = _comp.get("name", "")
                _rmc = _comp.get("raw_mapping_config") or {}
                _split_lead_transpose[_name] = _rmc.get("applyTranspose", False)

        for comp in slide_spec.get("components", []):
            # ── Resolve active data source for this component ────────────
            # Components may carry their own data_source key (written by
            # save_proposed_configs_to_spec when analysis_ids differ per chart).
            _comp_ds = comp.get("data_source") or ds_key
            if _comp_ds and _comp_ds not in data_cache:
                _cl = data_sources.get(_comp_ds, {})
                if _cl:
                    print(f"  Fetching component data_source '{_comp_ds}': "
                          f"analysis={_cl.get('analysis_ids')}")
                    _, _cdf = fetch_synapse_data(_cl, force_fresh=force_fresh)
                    data_cache[_comp_ds] = _cdf
                    print(f"    -> {len(_cdf)} records")
                else:
                    data_cache[_comp_ds] = pd.DataFrame()
            df = data_cache.get(_comp_ds, pd.DataFrame())
            records_list = df.to_dict("records") if not df.empty else []
            _cl = data_sources.get(_comp_ds, {})
            # Resolve static-pin state per-component: trust the component's
            # own tag first, then its data_source lineage. Do NOT fall back
            # to slide_spec — slide-level static_time_period_ids is hoisted
            # from the slide's PRIMARY chart by build_full_spec, and using
            # it here makes every other component on the slide inherit a
            # pin it never had. Bug surfaced on Repatha ATU slide 11 where
            # one chart is pinned to Wave 7 but four label_tables flow
            # dynamically — without this fix the label_tables get
            # static_pinned_skipped and the slide is flagged static_review.
            lin_raw_static_names = (
                comp.get("static_time_period_names")
                or _cl.get("static_time_period_names")
            )
            lin_raw_static_ids = (
                comp.get("static_time_period_ids")
                or _cl.get("static_time_period_ids")
            )

            name = comp.get("name", "")
            ctype = comp.get("type", "")

            if comp.get("static"):
                slide_results["tables"].append({"name": name, "status": "static_skipped"})
                continue

            # ── Truly-static → skip refresh ──
            # A component is "frozen" only when it pins specific waves AND
            # has no live-wave intent. If `include_live_wave=True` or
            # `dynamic_latest_n>0` are set on the lineage, the user wants
            # the chart refreshed — the static IDs there mean "ALSO keep
            # these specific historical waves visible," not "skip refresh."
            # Repatha ATU slide 11/12 surfaced this: every component there
            # has static_ids=[Wave 7] AND dynamic_latest_n=1 AND
            # include_live_wave=True, meaning "show pinned Wave 7 plus
            # the latest live wave." Pre-fix: skipped as static. Post-fix:
            # refreshed as mixed.
            ds_force_refresh = bool(_cl.get("force_refresh", False))
            _has_live_intent = (
                bool(_cl.get("include_live_wave"))
                or (_cl.get("dynamic_latest_n") or 0) > 0
            )
            if (lin_raw_static_ids
                    and not ds_force_refresh
                    and not _has_live_intent):
                bucket = "charts" if ctype == "chart" else "tables"
                slide_results[bucket].append({
                    "name": name, "status": "static_pinned_skipped",
                })
                continue

            raw_pc = comp.get("raw_pivot_config")
            raw_mc = comp.get("raw_mapping_config")

            # Apply split-viz applyTranspose alignment (see _split_lead_transpose
            # build above): non-lead split members inherit the lead's value so
            # all shapes in the group render consistently.
            if (raw_mc and ctype == "chart"
                    and comp.get("split_order") is not None
                    and comp.get("split_order") > 0
                    and name in _split_lead_transpose):
                lead_t = _split_lead_transpose[name]
                if raw_mc.get("applyTranspose") != lead_t:
                    raw_mc = dict(raw_mc)
                    raw_mc["applyTranspose"] = lead_t

            # ── RAW CONNECTOR PATH ──
            # When a component has raw_pivot_config + raw_mapping_config at the
            # top level, use pivot_records_to_chart_data() for exact Connector
            # fidelity.  This handles connected slides.
            if raw_pc and raw_mc:
                from slidegen.synapse_chart_mapper import pivot_records_to_chart_data

                static_names = lin_raw_static_names
                chart_pattern = comp.get("chart_pattern", "")
                split_order = comp.get("split_order")
                rows_per_object = comp.get("rows_per_object")
                top_n_rows = comp.get("top_n_rows")

                if ctype == "chart":
                    # Ambiguous-tag short-circuit: if this chart shares
                    # its tag fingerprint with one or more sibling charts
                    # on the same slide AND the source had distinct
                    # values per shape, refusing to refresh and
                    # preserving source is the only safe choice. Surface
                    # so the user can fix the tag (add a per-chart
                    # filter or split_order).
                    if name in _ambiguous_chart_keys:
                        slide_results["charts"].append({
                            "name": name, "status": "ambiguous_tag",
                            "notes": [{
                                "kind": "ambiguous_tag",
                                "detail": (
                                    "Multiple charts on this slide share "
                                    "identical connector tags but had "
                                    "different source values. Spec cannot "
                                    "differentiate them — preserving "
                                    "source. Add a per-chart filter / "
                                    "split_order to enable refresh."
                                ),
                            }],
                        })
                        continue

                    # Position-aware: claim the specific Connector-split shape
                    # this spec component refers to (multiple shapes on one
                    # slide can share a name).
                    shape = _claim_shape(
                        chart_shape_pool, name,
                        pos=comp.get("position"),
                        shape_id=comp.get("shape_id"),
                    )
                    if not shape:
                        slide_results["charts"].append({"name": name, "status": "not_found"})
                        continue

                    # Read source chart's structure to use as the canonical
                    # cat/series list (Issues 5/7/10/11). Refresh aligns its
                    # output to source: drop new cats that weren't there,
                    # keep cats with no current data filled with None.
                    #
                    # Position-aware source-shape lookup: when split-viz
                    # creates multiple shapes sharing a name, match by
                    # (left, top) so each spec component gets its OWN
                    # source shape (and therefore its OWN source series
                    # name like "CR6", "CR10", etc.). Without this, every
                    # component would inherit the first matching shape's
                    # source data and mass-assign the same series.
                    src_cats: list[str] | None = None
                    src_series_names: list[str] | None = None
                    src_series_values: list[list] | None = None
                    try:
                        comp_pos = comp.get("position") or {}
                        comp_l = float(comp_pos.get("left", 0) or 0)
                        comp_t = float(comp_pos.get("top", 0) or 0)
                        candidates = [
                            ss for ss in src_prs.slides[si].shapes
                            if ss.has_chart and ss.name == name
                        ]
                        if len(candidates) > 1 and (comp_l or comp_t):
                            best = min(
                                candidates,
                                key=lambda ss: (
                                    abs(((ss.left or 0) / 914400) - comp_l)
                                    + abs(((ss.top or 0) / 914400) - comp_t)
                                ),
                            )
                            candidates = [best]
                        for ss in candidates:
                            if True:
                                _plot = ss.chart.plots[0]
                                src_cats = [str(c) for c in (_plot.categories or [])]
                                src_series_names = [
                                    s.name if s.name else "" for s in _plot.series
                                ]
                                src_series_values = [
                                    list(s.values) for s in _plot.series
                                ]
                                break
                    except Exception:
                        src_cats = None
                        src_series_names = None
                        src_series_values = None

                    try:
                        chart_data = pivot_records_to_chart_data(
                            records_list, raw_pc, raw_mc,
                            static_time_period_names=static_names,
                            chart_pattern=chart_pattern,
                            split_order=split_order,
                            rows_per_object=rows_per_object,
                            top_n_rows=top_n_rows,
                            static_time_period_ids=lin_raw_static_ids,
                            known_wave_labels=_get_known_wave_labels(_comp_ds)
                                if _comp_ds else None,
                            source_categories=src_cats,
                            source_series_names=src_series_names,
                            source_series_values=src_series_values,
                        )

                        if not chart_data.success or not chart_data.categories:
                            # Pattern 4: distinguish "no data was fetched" from
                            # "fetch returned data but mapper couldn't fit it".
                            # The first means the shifted wave window has no
                            # data for this analysis × segment combo — chart
                            # legitimately can't be refreshed; preserve source
                            # and emit a visible warning so the eval can
                            # classify separately from genuine mapper failures.
                            err = chart_data.error or ""
                            if "alignment_failed" in err:
                                # API returned records but no source series
                                # could be aligned — chart kept at source
                                # values (mapper preserves them). Worth its own
                                # status so the eval can audit recoverability.
                                status = "alignment_failed"
                            elif df.empty:
                                status = "no_data_for_shifted_window"
                                if ds_force_refresh:
                                    print(f"  [warn] slide {si} {name!r} ({_comp_ds}): "
                                          f"shifted-wave fetch returned no records — "
                                          f"preserving source values")
                            else:
                                status = "empty"
                            slide_results["charts"].append({
                                "name": name, "status": status,
                                "error": chart_data.error,
                            })
                            continue

                        cats = chart_data.categories
                        series_data = chart_data.series

                        # Reorder categories to match source chart's order
                        # (pivot may return alphabetical; source has Connector's order)
                        try:
                            src_chart = None
                            for ss in src_prs.slides[si].shapes:
                                if ss.has_chart and ss.name == name:
                                    src_chart = ss
                                    break
                            if src_chart:
                                src_cats = [str(c) for c in src_chart.chart.plots[0].categories]
                                if set(src_cats) == set(cats) and src_cats != cats:
                                    order = [cats.index(sc) for sc in src_cats if sc in cats]
                                    if len(order) == len(cats):
                                        cats = [cats[i] for i in order]
                                        series_data = [(n, [v[i] for i in order])
                                                       for n, v in series_data]
                        except Exception:
                            pass

                        # Save formatCodes from source chart BEFORE replace_data
                        src_fmts = [
                            fc.text for fc in shape.chart._chartSpace.iter(
                                f"{{{ns_c}}}formatCode")
                        ]

                        # ── formatCode-aware value scaling ──
                        # Source charts can encode percentages two ways:
                        #   formatCode "0%"   → cell stores 0.45, displays 45%
                        #   formatCode "0.0"  → cell stores 45,  displays 45.0
                        # The mapper produces decimal-scale (0-1) values from
                        # the API's `decimal` column. Writing 0.45 into a chart
                        # whose formatCode is "0.0" displays "0.5" — the user's
                        # report of "everything changes to decimals on refresh".
                        # If the chart-wide formatCode lacks a percent sign, scale
                        # decimal-range values up by 100 so the display matches
                        # the source format.
                        _scale_to_whole_percent = False
                        if src_fmts:
                            non_pct = [fc for fc in src_fmts
                                       if fc and "%" not in fc and fc != "General"]
                            if non_pct and len(non_pct) >= max(1, len(src_fmts) // 2):
                                # Majority of formatCodes lack %; treat as whole-percent scale
                                _scale_to_whole_percent = True

                        # Detect inverse case: source formatCodes are mostly
                        # "0%" / "0.0%" (decimal-scale) but API may return
                        # whole-percent values. Without scaling, writing 88.31
                        # into a "0%"-formatted scatter chart renders as
                        # "8831%" (Repatha ATU slide 20 symptom).
                        _scale_to_decimal = False
                        if src_fmts:
                            pct_fmts = [f for f in src_fmts
                                        if f and "%" in f]
                            if pct_fmts and len(pct_fmts) >= max(1, len(src_fmts) // 2):
                                _scale_to_decimal = True

                        # Scatter charts have separate formatCodes for X and Y
                        # axes — typically "0%" for X (the actual metric) and
                        # "0" for Y (position labels). The whole-percent rule
                        # above can flip True for these because half the format
                        # codes lack "%", but applying *100 to the X data
                        # corrupts the chart (0.88 -> 88, then "0%" renders as
                        # "8800%"). For scatter, override the rule: if ANY
                        # formatCode contains "%", treat values as decimal-
                        # scale and skip the *100 scaling.
                        is_scatter = (
                            "scatter" in (chart_pattern or "")
                            or "xy_" in (chart_pattern or "")
                        )
                        if is_scatter and src_fmts and any(
                            "%" in (f or "") for f in src_fmts
                        ):
                            _scale_to_whole_percent = False

                        def _scale_val(v):
                            if v is None: return None
                            try:
                                fv = float(v)
                            except (TypeError, ValueError):
                                return v
                            # Source is whole-percent format and API gave decimal:
                            # 0-1 -> 0-100.
                            if _scale_to_whole_percent and abs(fv) <= 1.5:
                                return round(fv * 100, 4)
                            # Source is decimal-percent format ("0%") and API
                            # gave whole-percent: 0-100 -> 0-1.
                            if _scale_to_decimal and abs(fv) > 1.5:
                                return round(fv / 100, 4)
                            return round(fv, 4)

                        # Build chart data object
                        chart_type_str = chart_pattern
                        if "scatter" in chart_type_str or "xy_" in chart_type_str:
                            # XY scatter / abacus: sort by first series value desc
                            cd = XyChartData()
                            n_cats = len(cats)
                            if series_data and series_data[0][1]:
                                order = sorted(
                                    range(n_cats),
                                    # None-safe: treat missing values as 0 for
                                    # sort-only purposes; the actual data
                                    # point still uses the original (or 0
                                    # if None — see x_val below).
                                    key=lambda i: (
                                        (series_data[0][1][i]
                                         if i < len(series_data[0][1]) else 0)
                                        or 0
                                    ),
                                    reverse=True,
                                )
                            else:
                                order = list(range(n_cats))
                            for sname, vals in series_data:
                                s = cd.add_series(sname)
                                for rank, oi in enumerate(order):
                                    raw = vals[oi] if oi < len(vals) else None
                                    scaled = _scale_val(raw)
                                    x_val = scaled if scaled is not None else 0.0
                                    y_val = float(n_cats - rank)
                                    s.add_data_point(x_val, y_val)
                        else:
                            # Standard CategoryChartData
                            cd = CategoryChartData()
                            cd.categories = cats
                            for sname, vals in series_data:
                                cd.add_series(
                                    sname,
                                    [_scale_val(v) for v in vals],
                                )

                        shape.chart.replace_data(cd)

                        # Restore formatCodes from source (replace_data resets them)
                        for i, fc_el in enumerate(
                            shape.chart._chartSpace.iter(f"{{{ns_c}}}formatCode")
                        ):
                            if i < len(src_fmts):
                                fc_el.text = src_fmts[i]

                        chart_entry = {
                            "name": name, "status": "ok",
                            "categories": len(cats), "series": len(series_data),
                            "mode": "raw_connector",
                        }
                        if getattr(chart_data, "notes", None):
                            chart_entry["notes"] = list(chart_data.notes)
                        slide_results["charts"].append(chart_entry)
                    except Exception as e:
                        slide_results["charts"].append({
                            "name": name, "status": "error", "error": str(e),
                            "mode": "raw_connector",
                        })

                elif ctype in ("value_table", "label_table", "table"):
                    # Prefer shape_id-based lookup; fall back to name+pos.
                    # Without this, dense table layouts (Repatha ATU 11/12)
                    # can map a tag to the wrong physical table.
                    shape = _claim_shape(
                        table_shape_pool, name,
                        pos=comp.get("position"),
                        shape_id=comp.get("shape_id"),
                    )
                    if not shape:
                        slide_results["tables"].append({"name": name, "status": "not_found"})
                        continue

                    tbl = shape.table

                    # ── CELL VALUES PATH ──
                    # When cell_values is present (written by Claude after
                    # interpreting table_description + Synapse data), write
                    # them directly into the table cells.
                    #
                    # Dynamic sizing: cell_values drives the row/column count.
                    # If more rows are needed, clone the last row via lxml.
                    # Headers are controlled by source_snapshot — if the source
                    # had headers, cell_values[0] is treated as a header row.
                    cell_values = comp.get("cell_values")

                    # Auto-compute cell_values from the connector pivot when
                    # the spec doesn't carry them. Without this fallback,
                    # connected tables (label_table / value_table with
                    # raw_pivot_config) get marked "ok" but never actually
                    # have new data written into the cells — slide 11
                    # tables on Repatha ATU stayed source-identical despite
                    # the chart pipeline producing correct refreshed values.
                    raw_pc_t = comp.get("raw_pivot_config")
                    raw_mc_t = comp.get("raw_mapping_config")
                    if not cell_values and raw_pc_t and raw_mc_t:
                        try:
                            from slidegen.synapse_chart_mapper import pivot_records_to_chart_data
                            ds_for_t = comp.get("data_source") or ds_key
                            df_t = data_cache.get(ds_for_t, pd.DataFrame())
                            recs_t_list = (
                                df_t.to_dict("records")
                                if hasattr(df_t, "to_dict") else list(df_t)
                            )
                            chart_data_t = pivot_records_to_chart_data(
                                recs_t_list, raw_pc_t, raw_mc_t,
                                static_time_period_ids=lin_raw_static_ids,
                            )
                            if chart_data_t.success and chart_data_t.categories:
                                auto_cv = _auto_compute_cell_values(
                                    shape,
                                    chart_data_t.categories,
                                    chart_data_t.series,
                                    raw_pc_t,
                                    raw_mc_t,
                                    filtered_records=df_t,
                                )
                                if auto_cv:
                                    cell_values = auto_cv
                        except Exception:
                            pass

                    if cell_values:
                        try:
                            from copy import deepcopy
                            import random
                            tbl_xml = tbl._tbl
                            ns_a = "{http://schemas.openxmlformats.org/drawingml/2006/main}"
                            ns_a16 = "{http://schemas.microsoft.com/office/drawing/2014/main}"
                            xml_rows = tbl_xml.findall(f"{ns_a}tr")

                            needed_rows = len(cell_values)
                            current_rows = len(xml_rows)

                            # Add rows if needed (clone last row)
                            while current_rows < needed_rows:
                                new_row = deepcopy(xml_rows[-1])
                                # Generate a unique a16:rowId to prevent
                                # Connector from treating cloned rows as
                                # duplicates of the source row.
                                row_id_el = new_row.find(f".//{ns_a16}rowId")
                                if row_id_el is not None:
                                    row_id_el.set("val", str(random.randint(1, 2**32 - 1)))
                                tbl_xml.append(new_row)
                                xml_rows = tbl_xml.findall(f"{ns_a}tr")
                                current_rows = len(xml_rows)

                            # Remove excess rows if data has fewer
                            while current_rows > needed_rows:
                                tbl_xml.remove(xml_rows[-1])
                                xml_rows = tbl_xml.findall(f"{ns_a}tr")
                                current_rows = len(xml_rows)

                            # Write cell values + mark unwritten data cells as "xx"
                            # Re-fetch python-pptx table reference after XML changes
                            tbl = shape.table
                            n_rows = len(tbl.rows)
                            n_cols = len(tbl.columns)
                            # Track which cells we explicitly write
                            written = set()
                            for r, row_vals in enumerate(cell_values):
                                for c, val in enumerate(row_vals):
                                    if r < n_rows and c < n_cols:
                                        _write_cell_text(tbl.cell(r, c), str(val))
                                        written.add((r, c))
                            # Any unwritten cell that had data → mark stale
                            # Numeric cells (stale data) → "xx", non-numeric (labels/headers) → retain
                            for r in range(n_rows):
                                for c in range(n_cols):
                                    if (r, c) not in written:
                                        existing = tbl.cell(r, c).text.strip()
                                        if not existing:
                                            continue
                                        cleaned = existing.replace(",", "").replace("%", "").replace("$", "").strip()
                                        try:
                                            float(cleaned)
                                            # Numeric — stale data, mark as xx
                                            _write_cell_text(tbl.cell(r, c), "xx")
                                        except ValueError:
                                            pass  # Non-numeric (label/header) — retain

                            slide_results["tables"].append({
                                "name": name, "status": "ok",
                                "mode": "cell_values",
                                "rows_written": needed_rows,
                                "rows_added": max(0, needed_rows - len(xml_rows)),
                            })
                        except Exception as e2:
                            slide_results["tables"].append({
                                "name": name, "status": "error", "error": str(e2),
                                "mode": "cell_values",
                            })
                        continue

                    # ── SOURCE RESTORE PATH ──
                    # For connected tables without cell_values, restore from
                    # source (reliable). Table refresh from pivot configs is
                    # complex and fragile across table types.
                    try:
                        src_tbl_shape = None
                        for s2 in src_prs.slides[si].shapes:
                            if s2.has_table and s2.name == name:
                                src_tbl_shape = s2
                                break
                        if src_tbl_shape:
                            src_tbl = src_tbl_shape.table
                            for r in range(min(len(src_tbl.rows), len(tbl.rows))):
                                for c in range(min(len(src_tbl.columns), len(tbl.columns))):
                                    _write_cell_text(
                                        tbl.cell(r, c),
                                        src_tbl.cell(r, c).text.strip(),
                                    )
                            slide_results["tables"].append({
                                "name": name, "status": "ok", "mode": "source_restore",
                            })
                        else:
                            slide_results["tables"].append({
                                "name": name, "status": "no_source",
                            })
                    except Exception as e2:
                        slide_results["tables"].append({
                            "name": name, "status": "error", "error": str(e2),
                        })

                continue  # skip to next component

            # ── INTERPRETED MAPPING PATH ──
            # When a component has data_mapping with row_field/series_column/value_field,
            # use the existing pandas-based pivot logic (non-connected slides).
            dm = comp.get("data_mapping", {})
            if not dm:
                continue

            # Apply filters
            sub = df.copy()
            seg = dm.get("segment_filter")
            if seg and "segment_1" in sub.columns:
                sub = sub[sub["segment_1"] == seg]

            # Single time period filter (exact match)
            tp = dm.get("time_period")
            if tp and "time_period_name" in sub.columns:
                sub = sub[sub["time_period_name"] == tp]

            if ctype == "chart":
                shape = chart_shapes.get(name)
                if not shape:
                    slide_results["charts"].append({"name": name, "status": "not_found"})
                    continue
                if sub.empty:
                    slide_results["charts"].append({"name": name, "status": "empty"})
                    continue

                row_f = dm.get("row_field", "y_label")
                col_f = dm.get("series_column")
                val_f = dm.get("value_field", "percentage")
                name_map = dm.get("series_name_map", {})

                try:
                    if col_f and col_f in sub.columns:
                        pivot = sub.pivot_table(index=row_f, columns=col_f,
                                                values=val_f, aggfunc="first")
                    else:
                        pivot = sub.groupby(row_f, sort=False)[val_f].first().to_frame()

                    categories = list(pivot.index.astype(str))

                    # Apply category order
                    cat_order = dm.get("category_order")
                    if cat_order:
                        order = [categories.index(c) for c in cat_order if c in categories]
                        extra = [i for i in range(len(categories)) if i not in order]
                        reorder = order + extra
                        categories = [categories[i] for i in reorder]
                        pivot = pivot.iloc[reorder]

                    orig_series = src_chart_series.get(name, [])
                    series_data = []
                    for sn in orig_series:
                        data_val = name_map.get(sn, sn)
                        matched = None
                        for pc in pivot.columns:
                            if str(pc) == data_val or str(pc).lower() == data_val.lower():
                                matched = pc
                                break
                        if matched is None and len(pivot.columns) == 1:
                            matched = pivot.columns[0]
                        vals = ([0.0 if pd.isna(v) else round(float(v), 4) for v in pivot[matched]]
                                if matched is not None else [0.0] * len(categories))
                        series_data.append((sn, vals))

                    # Save + restore formatCodes
                    src_fmts = [fc.text for fc in shape.chart._chartSpace.iter(f"{{{ns_c}}}formatCode")]
                    cd = CategoryChartData()
                    cd.categories = categories
                    for sn, vals in series_data:
                        cd.add_series(sn, vals)
                    shape.chart.replace_data(cd)
                    for i, fc_el in enumerate(shape.chart._chartSpace.iter(f"{{{ns_c}}}formatCode")):
                        if i < len(src_fmts):
                            fc_el.text = src_fmts[i]

                    slide_results["charts"].append({
                        "name": name, "status": "ok", "segment": seg,
                        "categories": len(categories), "series": len(series_data),
                    })
                except Exception as e:
                    slide_results["charts"].append({"name": name, "status": "error", "error": str(e)})

            elif ctype == "table":
                shape = table_shapes.get(name)
                if not shape:
                    slide_results["tables"].append({"name": name, "status": "not_found"})
                    continue

                tbl = shape.table
                columns_spec = dm.get("columns", [])
                if not columns_spec:
                    continue

                try:
                    all_have_filters = all(cs.get("filter") for cs in columns_spec if cs.get("data_field"))
                    row_key = None
                    if not all_have_filters:
                        for cs in columns_spec:
                            if cs.get("data_field") and cs.get("format") != "spacer":
                                row_key = cs["data_field"]
                                break

                    if all_have_filters and not row_key:
                        # Single-row summary table
                        target_row = 1 if len(tbl.rows) > 1 else 0
                        for ci, cs in enumerate(columns_spec):
                            if ci >= len(tbl.columns):
                                break
                            data_f = cs.get("data_field")
                            col_filter = cs.get("filter")
                            if not data_f:
                                continue
                            cell_sub = df.copy()
                            if tp and "time_period_name" in cell_sub.columns:
                                cell_sub = cell_sub[cell_sub["time_period_name"] == tp]
                            if col_filter:
                                for fk, fv in col_filter.items():
                                    if fk in cell_sub.columns:
                                        cell_sub = cell_sub[cell_sub[fk] == fv]
                            if cell_sub.empty or data_f not in cell_sub.columns:
                                continue
                            _write_cell_text(tbl.cell(target_row, ci),
                                             _format_cell(cell_sub.iloc[0][data_f], cs.get("format", "string")))

                        slide_results["tables"].append({"name": name, "status": "ok", "rows": 1})
                    else:
                        if not row_key or sub.empty or row_key not in sub.columns:
                            slide_results["tables"].append({"name": name, "status": "no_data"})
                            continue

                        # Apply table-level category order
                        cat_order = dm.get("category_order")
                        keys = sub[row_key].dropna().unique().tolist()
                        if cat_order:
                            ordered = [k for k in cat_order if k in keys]
                            extra = [k for k in keys if k not in ordered]
                            keys = ordered + extra

                        n_rows = min(len(keys), len(tbl.rows) - 1)
                        for ri in range(n_rows):
                            row_data = sub[sub[row_key] == keys[ri]]
                            if row_data.empty:
                                continue
                            for ci, cs in enumerate(columns_spec):
                                if ci >= len(tbl.columns) or ri + 1 >= len(tbl.rows):
                                    break
                                fmt = cs.get("format", "string")
                                data_f = cs.get("data_field")
                                col_filter = cs.get("filter")
                                if fmt == "spacer" or not data_f:
                                    continue
                                cell_data = row_data
                                if col_filter:
                                    for fk, fv in col_filter.items():
                                        if fk in cell_data.columns:
                                            cell_data = cell_data[cell_data[fk] == fv]
                                if cell_data.empty or data_f not in cell_data.columns:
                                    continue
                                _write_cell_text(tbl.cell(ri + 1, ci),
                                                 _format_cell(cell_data.iloc[0][data_f], fmt))

                        slide_results["tables"].append({"name": name, "status": "ok", "rows": n_rows})
                except Exception as e:
                    slide_results["tables"].append({"name": name, "status": "error", "error": str(e)})

        # ── Per-slide text replacement: old wave labels → new wave labels ──
        # When refresh shifts the chart's wave window (e.g. Feb-Mar → Mar-Apr),
        # any text shape on the slide that referenced the old waves should be
        # updated to match. Examples: object titles, legend hints, methodology
        # footnotes, "Wave X data only" annotations.
        # Also updates "n=NN" sample-size patterns where a single n value
        # applies to the whole slide.
        try:
            _update_slide_text_for_refresh(slide, src_prs.slides[si], slide_spec,
                                           data_cache, data_sources)
        except Exception as exc:
            print(f"  [warn] text-replacement on slide {si} failed: {exc}")

        all_results["slides"].append(slide_results)

    prs.save(output_path)
    return all_results


def _update_slide_text_for_refresh(out_slide, src_slide, slide_spec,
                                   data_cache, data_sources) -> None:
    """Update text shapes on a slide to reflect the refreshed wave window.

    Looks at the connected charts' source-vs-refreshed wave categories;
    builds a label map (old_label → new_label) per chart; and scans every
    text shape on the slide for occurrences of old labels, replacing them
    with the corresponding new labels.

    Also updates `n=\\d+` sample-size mentions when a single base value
    applies (single component on the slide).

    Conservative: only replaces standalone wave-label tokens, not arbitrary
    substrings — avoids accidental edits to message/option text that
    happens to share words with a wave label.
    """
    # Build per-chart label map by comparing src vs refreshed cats AND series
    # (waves can live on either axis depending on applyTranspose).
    src_charts_by_name: dict[str, list] = {}
    for sh in src_slide.shapes:
        if sh.has_chart:
            src_charts_by_name.setdefault(sh.name, []).append(sh)

    label_replacements: list[tuple[str, str]] = []
    for sh in out_slide.shapes:
        if not sh.has_chart:
            continue
        srcs = src_charts_by_name.get(sh.name, [])
        if not srcs:
            continue
        # Match by closest-position when multiple share a name (split-viz)
        sh_l = (sh.left or 0); sh_t = (sh.top or 0)
        src_sh = min(
            srcs,
            key=lambda s: abs((s.left or 0) - sh_l) + abs((s.top or 0) - sh_t),
        )
        try:
            src_cats = [str(c) for c in src_sh.chart.plots[0].categories]
            new_cats = [str(c) for c in sh.chart.plots[0].categories]
            src_series = [s.name for s in src_sh.chart.plots[0].series]
            new_series = [s.name for s in sh.chart.plots[0].series]
        except Exception:
            continue
        # Only build a mapping for the WAVE axis (skip non-wave dims).
        from slidegen.synapse_chart_mapper import _is_wave_label
        if src_cats and new_cats and all(_is_wave_label(c) for c in src_cats):
            for old, new in zip(src_cats, new_cats):
                if old != new:
                    label_replacements.append((old, new))
        if src_series and new_series and all(_is_wave_label(c) for c in src_series):
            for old, new in zip(src_series, new_series):
                if old != new:
                    label_replacements.append((old, new))

    # Add range replacements: "Oct'25 - Mar'26" → "Nov'25 - Apr'26" derived
    # from the first/last waves on a chart that used a wave dim.
    range_replacements: list[tuple[str, str]] = []
    for sh in out_slide.shapes:
        if not sh.has_chart:
            continue
        srcs = src_charts_by_name.get(sh.name, [])
        if not srcs:
            continue
        sh_l = (sh.left or 0); sh_t = (sh.top or 0)
        src_sh = min(
            srcs,
            key=lambda s: abs((s.left or 0) - sh_l) + abs((s.top or 0) - sh_t),
        )
        try:
            src_cats = [str(c) for c in src_sh.chart.plots[0].categories]
            new_cats = [str(c) for c in sh.chart.plots[0].categories]
        except Exception:
            continue
        from slidegen.synapse_chart_mapper import _is_wave_label
        if (src_cats and new_cats and len(src_cats) >= 2 and len(new_cats) >= 2
                and all(_is_wave_label(c) for c in src_cats)
                and all(_is_wave_label(c) for c in new_cats)):
            old_range = f"{src_cats[0]} - {src_cats[-1]}"
            new_range = f"{new_cats[0]} - {new_cats[-1]}"
            if old_range != new_range:
                range_replacements.append((old_range, new_range))
            # Also handle the reverse-spelled range
            old_range_rev = f"{src_cats[0]} – {src_cats[-1]}"  # en dash
            new_range_rev = f"{new_cats[0]} – {new_cats[-1]}"
            if old_range_rev != new_range_rev:
                range_replacements.append((old_range_rev, new_range_rev))

    if not label_replacements and not range_replacements:
        return

    # Apply replacements. Prefer ranges first (longer matches) then labels.
    seen = set()
    ordered = []
    for pair in range_replacements + label_replacements:
        if pair not in seen:
            seen.add(pair); ordered.append(pair)

    for sh in out_slide.shapes:
        if sh.has_chart or sh.has_table:
            continue
        if not sh.has_text_frame:
            continue
        tf = sh.text_frame
        for para in tf.paragraphs:
            for run in para.runs:
                txt = run.text
                if not txt:
                    continue
                new_txt = txt
                for old, new in ordered:
                    if old and old in new_txt:
                        new_txt = new_txt.replace(old, new)
                if new_txt != txt:
                    run.text = new_txt


def stamp_refresh_notes(pptx_path: str, refresh_results: dict) -> dict:
    """Stamp per-shape REFRESH_NOTE tags into a refreshed PPTX (in place).

    For every shape in `refresh_results["slides"][...]["charts"|"tables"]`
    that has a non-empty `notes` list, inject the following Connector-format
    tags into the shape's existing tag.xml file:

        <p:tag name="REFRESH_TIMESTAMP" val="2026-05-05T..."/>
        <p:tag name="REFRESH_STATUS"    val="ok"/>
        <p:tag name="REFRESH_NOTES"     val="kind1::detail1||kind2::detail2"/>

    Multi-note shapes get all notes joined with `||` in REFRESH_NOTES so a
    single tag entry covers them all (PowerPoint's tagLst format expects
    unique tag names).

    Idempotent within a single refresh: if a shape already has any of these
    three tags, they are replaced (not duplicated).

    Args:
        pptx_path:       PPTX to modify in place.
        refresh_results: Output of refresh_deck_from_spec, dict with key
                         "slides": [{"slide_index", "charts": [...], "tables": [...]}].

    Returns:
        {(slide_idx, shape_name): "stamped" | "shape_not_in_pptx" | "no_tag_file"}
    """
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.0000000Z")
    stamps: dict[tuple[int, str], str] = {}

    # Collect (slide_idx, shape_name) -> notes payload to stamp
    targets: dict[int, list[tuple[str, str, list[dict]]]] = {}
    for slide_entry in refresh_results.get("slides", []):
        si = slide_entry.get("slide_index")
        if si is None:
            continue
        for comp in (slide_entry.get("charts") or []) + (slide_entry.get("tables") or []):
            notes = comp.get("notes") or []
            status = comp.get("status", "")
            if not notes:
                # Only stamp shapes that actually have annotations to record;
                # otherwise we'd bloat every connected shape's tag.xml on every
                # refresh. Status-only entries (e.g. plain "ok") are not stamped.
                continue
            name = comp.get("name", "")
            if not name:
                continue
            targets.setdefault(si, []).append((name, status, notes))

    if not targets:
        return stamps

    with zipfile.ZipFile(pptx_path, "r") as zf:
        all_entries: dict[str, bytes] = {n: zf.read(n) for n in zf.namelist()}

    for si, shapes_to_stamp in targets.items():
        slide_file = f"ppt/slides/slide{si + 1}.xml"
        rels_file = f"ppt/slides/_rels/slide{si + 1}.xml.rels"
        if slide_file not in all_entries:
            for nm, _, _ in shapes_to_stamp:
                stamps[(si, nm)] = "shape_not_in_pptx"
            continue

        slide_xml = all_entries[slide_file].decode("utf-8")
        rels_xml = all_entries.get(rels_file, b"").decode("utf-8")

        rid_to_tag: dict[str, str] = {}
        for m in re.finditer(
            r'Id="(rId\d+)"[^>]*Target="(\.\./tags/tag\d+\.xml)"', rels_xml
        ):
            rid_to_tag[m.group(1)] = "ppt/tags/" + m.group(2).split("/")[-1]

        shape_to_tag: dict[str, str] = {}
        for m in re.finditer(
            r'<p:cNvPr[^>]*\bname="([^"]*)"[^>]*/?>.*?<p:tags\s+r:id="(rId\d+)"\s*/>',
            slide_xml, re.DOTALL,
        ):
            shape_to_tag[m.group(1)] = rid_to_tag.get(m.group(2), "")

        for shape_name, status, notes in shapes_to_stamp:
            tag_file = shape_to_tag.get(shape_name)
            if not tag_file or tag_file not in all_entries:
                stamps[(si, shape_name)] = "no_tag_file"
                continue

            notes_value = "||".join(
                f"{n.get('kind', 'unknown')}::{(n.get('detail') or '')[:300]}"
                for n in notes
            )
            new_tags = (
                f'<p:tag name="REFRESH_TIMESTAMP" val="{_escape_attr(timestamp)}"/>'
                f'<p:tag name="REFRESH_STATUS" val="{_escape_attr(status)}"/>'
                f'<p:tag name="REFRESH_NOTES" val="{_escape_attr(notes_value)}"/>'
            )

            tag_xml = all_entries[tag_file].decode("utf-8")
            # Replace existing tags with same name, then inject new
            for tag_name in ("REFRESH_TIMESTAMP", "REFRESH_STATUS", "REFRESH_NOTES"):
                tag_xml = re.sub(
                    rf'<p:tag\s+name="{tag_name}"\s+val="[^"]*"\s*/>',
                    "", tag_xml,
                )
            tag_xml = tag_xml.replace("</p:tagLst>", new_tags + "</p:tagLst>")
            all_entries[tag_file] = tag_xml.encode("utf-8")
            stamps[(si, shape_name)] = "stamped"

    tmp_path = pptx_path + ".tmp"
    with zipfile.ZipFile(tmp_path, "w", zipfile.ZIP_DEFLATED) as zout:
        for name, data in all_entries.items():
            zout.writestr(name, data)
    os.replace(tmp_path, pptx_path)

    return stamps


