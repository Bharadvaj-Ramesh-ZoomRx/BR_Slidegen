# Namespace for our Custom XML Part (distinguishes from Connector's parts)
SLIDEGEN_CONFIG_NS = "http://slidegen.zoomrx.com/config"


# ══════════════════════════════════════════════════════════════════════════════
# Embedded Config — read/write lightweight config inside PPTX
# ══════════════════════════════════════════════════════════════════════════════

def read_embedded_config(pptx_path: str) -> dict | None:
    """Read the SlideGen config embedded in a PPTX as a Custom XML Part.

    Returns the config dict, or None if no SlideGen config is embedded.
    """
    try:
        with zipfile.ZipFile(pptx_path, "r") as z:
            for name in z.namelist():
                if not name.startswith("customXml/item") or not name.endswith(".xml"):
                    continue
                if "Props" in name:
                    continue
                blob = z.read(name).decode("utf-8", errors="replace")
                if SLIDEGEN_CONFIG_NS in blob:
                    # Extract JSON between the XML tags
                    start = blob.index("{")
                    end = blob.rindex("}") + 1
                    return json.loads(blob[start:end])
    except Exception:
        pass
    return None


def write_embedded_config(pptx_path: str, config: dict) -> None:
    """Write (or overwrite) the SlideGen config as a Custom XML Part in the PPTX.

    The config is stored as JSON inside an XML wrapper with our namespace.
    If a SlideGen config already exists, it is replaced. Otherwise, a new
    Custom XML Part is added.
    """
    config_json = json.dumps(config, indent=2, ensure_ascii=False)
    config_xml = (
        f'<SlideGenConfig xmlns="{SLIDEGEN_CONFIG_NS}">'
        f"{config_json}"
        f"</SlideGenConfig>"
    )

    item_id = str(uuid.uuid4()).upper()
    props_xml = (
        f'<?xml version="1.0" encoding="UTF-8" standalone="no"?>'
        f'<ds:datastoreItem ds:itemID="{{{item_id}}}" '
        f'xmlns:ds="http://schemas.openxmlformats.org/officeDocument/2006/customXml">'
        f'<ds:schemaRefs>'
        f'<ds:schemaRef ds:uri="{SLIDEGEN_CONFIG_NS}"/>'
        f'</ds:schemaRefs>'
        f'</ds:datastoreItem>'
    )

    tmp_path = pptx_path + ".tmp"
    existing_item = None

    with zipfile.ZipFile(pptx_path, "r") as zin:
        # Find existing SlideGen config part (if any)
        for name in zin.namelist():
            if name.startswith("customXml/item") and name.endswith(".xml") and "Props" not in name:
                blob = zin.read(name).decode("utf-8", errors="replace")
                if SLIDEGEN_CONFIG_NS in blob:
                    existing_item = name
                    break

        with zipfile.ZipFile(tmp_path, "w", zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                if existing_item and item.filename == existing_item:
                    # Replace existing config
                    zout.writestr(item, config_xml.encode("utf-8"))
                elif existing_item and item.filename == existing_item.replace("item", "itemProps"):
                    zout.writestr(item, props_xml.encode("utf-8"))
                else:
                    zout.writestr(item, zin.read(item.filename))

            if not existing_item:
                # Add new part — find next available number
                existing_nums = []
                for n in zin.namelist():
                    if n.startswith("customXml/item") and n.endswith(".xml") and "Props" not in n:
                        try:
                            num = int(n.replace("customXml/item", "").replace(".xml", ""))
                            existing_nums.append(num)
                        except ValueError:
                            pass
                next_num = max(existing_nums, default=0) + 1
                zout.writestr(f"customXml/item{next_num}.xml", config_xml.encode("utf-8"))
                zout.writestr(f"customXml/itemProps{next_num}.xml", props_xml.encode("utf-8"))

    os.replace(tmp_path, pptx_path)


def generate_embedded_config(pptx_path: str) -> dict:
    """Generate a config from the current state of a PPTX.

    Scans all slides: assigns a stable ID to each, detects charts/tables,
    and creates a lightweight manifest. Does NOT determine data_source
    assignments — that's Claude Code's job.
    """
    prs = Presentation(pptx_path)
    slides = []

    for si, slide in enumerate(prs.slides):
        n_charts = sum(1 for s in slide.shapes if s.has_chart)
        n_tables = sum(1 for s in slide.shapes if s.has_table)

        # Extract headline for identification
        headline = ""
        for shape in slide.shapes:
            if shape.has_text_frame:
                top = round((shape.top or 0) / 914400, 2)
                text = shape.text_frame.text.strip()
                if top < 1.5 and len(text) > len(headline):
                    headline = text

        # Collect shape names (stable identifiers for components)
        components = []
        for shape in slide.shapes:
            if shape.has_chart:
                components.append({"type": "chart", "name": shape.name})
            elif shape.has_table:
                components.append({"type": "table", "name": shape.name})

        slides.append({
            "id": f"slide_{si:03d}",
            "index": si,
            "headline": headline[:100],
            "charts": n_charts,
            "tables": n_tables,
            "components": components,
            "data_source": None,  # Claude Code fills this in
        })

    return {
        "version": "1.0",
        "source_deck": Path(pptx_path).name,
        "total_slides": len(prs.slides),
        "slides": slides,
        "data_sources": {},
    }


def reconcile_spec_with_config(spec: dict, config: dict) -> dict:
    """Reconcile a spec.json against the PPTX's embedded config.

    Detects:
    - Reordered slides (slide_id moved to a different index)
    - Added slides (in config but not in spec)
    - Deleted slides (in spec but not in config)

    Returns an updated spec with corrected slide_index values and
    flags for added/deleted slides.
    """
    config_slides = {s["id"]: s for s in config.get("slides", [])}
    spec_slides = {s.get("slide_id", f"slide_{s['slide_index']:03d}"): s
                   for s in spec.get("slides", [])}

    updated_slides = []
    changes = {"reordered": [], "added": [], "deleted": [], "unchanged": []}

    # Match spec slides to config slides by ID
    for cfg_slide in config.get("slides", []):
        sid = cfg_slide["id"]
        new_index = cfg_slide["index"]

        if sid in spec_slides:
            s = spec_slides[sid]
            old_index = s["slide_index"]
            s["slide_index"] = new_index
            if old_index != new_index:
                changes["reordered"].append({"id": sid, "old": old_index, "new": new_index})
            else:
                changes["unchanged"].append(sid)
            updated_slides.append(s)
        else:
            # New slide — add placeholder
            changes["added"].append({"id": sid, "index": new_index,
                                     "headline": cfg_slide.get("headline", "")})
            updated_slides.append({
                "slide_id": sid,
                "slide_index": new_index,
                "data_source": cfg_slide.get("data_source"),
                "components": [],
                "_needs_interpretation": True,
            })

    # Find deleted slides (in spec but not in config)
    config_ids = set(s["id"] for s in config.get("slides", []))
    for sid, s in spec_slides.items():
        if sid not in config_ids:
            changes["deleted"].append({"id": sid, "index": s["slide_index"]})

    spec["slides"] = updated_slides
    # Merge data_sources from config into spec
    for key, val in config.get("data_sources", {}).items():
        if key not in spec.get("data_sources", {}):
            spec.setdefault("data_sources", {})[key] = val

    return {"spec": spec, "changes": changes}

_CHART_TYPE_MAP = {
    XL_CHART_TYPE.BAR_STACKED_100: "bar_stacked_100_horizontal",
    XL_CHART_TYPE.BAR_CLUSTERED: "bar_clustered_horizontal",
    XL_CHART_TYPE.COLUMN_CLUSTERED: "column_clustered_vertical",
    XL_CHART_TYPE.COLUMN_STACKED_100: "column_stacked_100_vertical",
    XL_CHART_TYPE.LINE_MARKERS: "line_markers_trended",
    XL_CHART_TYPE.LINE: "line_markers_trended",
    XL_CHART_TYPE.XY_SCATTER: "xy_scatter_abacus",
    XL_CHART_TYPE.DOUGHNUT: "doughnut_default",
}


def _in(emu):
    """Convert EMU to inches, rounded to 2 decimal places."""
    return round(emu / 914400, 2) if emu else 0.0


